// Turn ../spec/profiles/*.yaml into src/profiles/data.ts so the package needs no YAML parser at runtime,
// and write src/version.ts from package.json so the version has one source.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
const spec = resolve(here, "..", "..", "spec", "profiles");
const out = resolve(here, "..", "src", "profiles", "data.ts");

const files = readdirSync(spec).filter((f) => f.endsWith(".yaml")).sort();
const profiles = files.map((f) => parse(readFileSync(join(spec, f), "utf-8")));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/build-profiles.mjs from spec/profiles. Do not edit.\n` +
    `export const PROFILE_DATA: Record<string, unknown>[] = ${JSON.stringify(profiles, null, 2)};\n`,
);
console.log(`${profiles.length} profiles -> ${out}`);

const pkg = JSON.parse(readFileSync(resolve(here, "..", "package.json"), "utf-8"));
const versionOut = resolve(here, "..", "src", "version.ts");
writeFileSync(versionOut, `// Generated by scripts/build-profiles.mjs from package.json. Do not edit.\nexport const version = ${JSON.stringify(pkg.version)};\n`);
console.log(`version ${pkg.version} -> ${versionOut}`);
